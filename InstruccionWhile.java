public class InstruccionWhile {
    public static void main(String[] args) {
        int numero = 1;

        // Bucle while para imprimir del 1 al 10
        while (numero <= 10) {
            System.out.println("Texto " + numero);
            numero++; // Equivale a: numero = numero + 1;
        }
    } // Fin del método main
} // Fin de la clase InstruccionWhile