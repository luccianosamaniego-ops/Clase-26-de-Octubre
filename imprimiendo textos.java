public class ImprimiendoTextos {
    public static void main(String[] args) {
        // Usamos un bucle for para automatizar la impresión del 1 al 10
        for (int i = 1; i <= 10; i++) {
            System.out.println("Texto " + i);
        }
    } // Fin del método main
} // Fin de la clase ImprimiendoTextos